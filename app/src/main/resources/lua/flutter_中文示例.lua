end

activity.setContentView(渲染Flutter(页面()))

function 收到Flutter事件(e)
  local 名 = (e and e.name) or "?"
  local 数据 = (e and e.data) or {}

  if 名 == "输入昵称" then
    print("输入：" .. tostring(数据.value))
    return   -- 输入时不重绘，避免打断输入
  end

  local 消息 = "事件：" .. 名
  if 数据.action and 数据.action ~= "" then 消息 = 消息 .. "  方法=" .. 数据.action end
  if 数据.value ~= nil then 消息 = 消息 .. "  值=" .. tostring(数据.value) end
  if 数据.result then
    if 数据.result.name then 消息 = 消息 .. "  名字=" .. tostring(数据.result.name) end
    if 数据.result.result then 消息 = 消息 .. "  结果=" .. tostring(数据.result.result) end
    if 数据.result.pong ~= nil then 消息 = 消息 .. "  pong=" .. tostring(数据.result.pong) end
    if 数据.result.text then 消息 = 消息 .. "  文本=" .. tostring(数据.result.text) end
  end
  提示 = 消息

  -- 演示异步 dartCall：回调在主线程执行，可安全刷新 UI
  if 名 == "异步加" then
    调用Dart("getUserInfo", { id = 9 }, function(结果, 错误)
      if 结果 then
        提示 = "异步返回：name=" .. tostring(结果.name) .. "，add 结果=" .. tostring(数据.result.result)
      else
        提示 = "异步出错：" .. tostring(错误)
      end
      重绘()
    end)
    return
  end

  重绘()
end
